create or replace function public.pay_invoice(invoice_id bigint)
returns public.invoices
language plpgsql
security definer
set search_path = public
as $$
declare
  invoice_row public.invoices;
  sender public.accounts;
  receiver public.accounts;
begin
  select * into invoice_row from public.invoices where id = invoice_id for update;
  if not found then raise exception 'Rechnung nicht gefunden'; end if;
  if invoice_row.status <> 'open' then raise exception 'Rechnung ist bereits bearbeitet'; end if;

  select * into sender from public.accounts where id = invoice_row.from_account_id for update;
  select * into receiver from public.accounts where id = invoice_row.to_account_id for update;
  if sender.status <> 'active' or receiver.status <> 'active' then
    raise exception 'Beide Konten muessen aktiv sein';
  end if;
  if sender.balance < invoice_row.amount then raise exception 'Guthaben reicht nicht aus'; end if;

  update public.accounts set balance = balance - invoice_row.amount where id = sender.id;
  update public.accounts set balance = balance + invoice_row.amount where id = receiver.id;
  update public.invoices set status = 'paid', paid_at = now() where id = invoice_row.id returning * into invoice_row;
  return invoice_row;
end;
$$;

create or replace function public.create_order(account_id bigint, items_json jsonb, total_amount numeric)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  account_row public.accounts;
  order_row public.orders;
begin
  if total_amount is null or total_amount <= 0 then raise exception 'Bestellwert muss groesser als 0 sein'; end if;
  if items_json is null or jsonb_typeof(items_json) <> 'array' or jsonb_array_length(items_json) = 0 then
    raise exception 'Warenkorb ist leer';
  end if;
  select * into account_row from public.accounts where id = account_id for update;
  if not found or account_row.status <> 'active' then raise exception 'Konto ist nicht aktiv'; end if;
  if account_row.balance < total_amount then raise exception 'Guthaben reicht nicht aus'; end if;

  update public.accounts set balance = balance - total_amount where id = account_row.id;
  insert into public.orders(account_id, items_json, total_amount, status)
    values (account_row.id, items_json, total_amount, 'paid') returning * into order_row;
  return order_row;
end;
$$;

create or replace function public.create_order_with_delivery(
  account_id bigint,
  items_json jsonb,
  subtotal numeric,
  delivery_method text,
  delivery_location text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  account_row public.accounts;
  order_row public.orders;
  seller_account public.accounts;
  final_amount numeric := subtotal;
  fee numeric := 0;
begin
  if subtotal is null or subtotal <= 0 then raise exception 'Bestellwert muss groesser als 0 sein'; end if;
  if items_json is null or jsonb_typeof(items_json) <> 'array' or jsonb_array_length(items_json) = 0 then
    raise exception 'Warenkorb ist leer';
  end if;
  if delivery_method not in ('abholung', 'transport') then raise exception 'Ungueltige Lieferart'; end if;
  if delivery_method = 'transport' then
    if delivery_location is null or length(trim(delivery_location)) = 0 then raise exception 'Lieferort fehlt'; end if;
    fee := 2000;
    final_amount := subtotal + fee;
  end if;

  select * into account_row from public.accounts where id = account_id for update;
  if not found or account_row.status <> 'active' then raise exception 'Konto ist nicht aktiv'; end if;
  if account_row.balance < final_amount then raise exception 'Guthaben reicht nicht aus'; end if;

  update public.accounts set balance = balance - final_amount where id = account_row.id;
  select accounts.* into seller_account
    from public.accounts
    join public.companies on companies.id = accounts.company_id
    where lower(companies.company_name) = 'mezzorik logistik' and accounts.type = 'unternehmen' and accounts.status = 'active'
    limit 1
    for update;
  if not found then raise exception 'Mezzorik-Konto ist nicht aktiv'; end if;
  update public.accounts set balance = balance + final_amount where id = seller_account.id;
  insert into public.orders(account_id, items_json, total_amount, status, delivery_method, transport_fee, transport_status)
    values (account_row.id, items_json, final_amount, 'paid', delivery_method, fee, case when delivery_method = 'transport' then 'offen' else 'nicht_erforderlich' end)
    returning * into order_row;

  if delivery_method = 'transport' then
    insert into public.transport_jobs(order_id, account_id, item_name, quantity, items_json, delivery_location, status, transport_fee)
      values (order_row.id, account_row.id, 'Katalogbestellung', jsonb_array_length(items_json), items_json, trim(delivery_location), 'offen', fee);
  end if;
  return order_row;
end;
$$;

create or replace function public.update_transport_status(transport_job_id bigint, next_status text)
returns public.transport_jobs
language plpgsql
security definer
set search_path = public
as $$
declare
  job public.transport_jobs;
  item jsonb;
  requested_quantity integer;
  current_quantity integer;
begin
  if next_status not in ('offen', 'angenommen', 'beladen', 'unterwegs', 'erledigt', 'storniert') then
    raise exception 'Ungueltiger Transportstatus';
  end if;

  select * into job from public.transport_jobs where id = transport_job_id for update;
  if not found then raise exception 'Transportauftrag nicht gefunden'; end if;

  if next_status = 'angenommen' and not job.stock_deducted then
    for item in select * from jsonb_array_elements(job.items_json)
    loop
      requested_quantity := greatest(1, coalesce((item->>'order_quantity')::integer, 1));
      if item->>'source' = 'company' then
        select amount into current_quantity from public.company_warehouse where id = (item->>'id')::bigint for update;
        if current_quantity is null or current_quantity < requested_quantity then raise exception 'Nicht genuegend Firmenbestand fuer %', item->>'item_name'; end if;
        update public.company_warehouse set amount = amount - requested_quantity where id = (item->>'id')::bigint;
      else
        select quantity into current_quantity from public.logistics_items where id = (item->>'id')::bigint for update;
        if current_quantity is null or current_quantity < requested_quantity then raise exception 'Nicht genuegend Lagerbestand fuer %', item->>'item_name'; end if;
        update public.logistics_items set quantity = quantity - requested_quantity where id = (item->>'id')::bigint;
      end if;
    end loop;
  end if;

  update public.transport_jobs set status = next_status, stock_deducted = stock_deducted or next_status = 'angenommen' where id = transport_job_id returning * into job;
  if job.order_id is not null then
    update public.orders set transport_status = case next_status when 'angenommen' then 'bestaetigt' when 'beladen' then 'bestaetigt' when 'unterwegs' then 'unterwegs' when 'erledigt' then 'zugestellt' when 'storniert' then 'storniert' else 'offen' end where id = job.order_id;
  end if;
  return job;
end;
$$;

