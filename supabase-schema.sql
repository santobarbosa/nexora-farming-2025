do $$
declare
  table_name text;
begin
  foreach table_name in array array['citizens','companies','accounts','invoices','vehicles','licenses','logistics','logistics_items','orders'] loop
    execute format('drop policy if exists %I on public.%I', 'dev_public_access_' || table_name, table_name);
    execute format('create policy %I on public.%I for all to anon, authenticated using (true) with check (true)', 'dev_public_access_' || table_name, table_name);
  end loop;
end;
$$;

