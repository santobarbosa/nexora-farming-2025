create or replace function public.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  row_data jsonb := case when TG_OP = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  insert into public.audit_log(user_id, username, action, table_name, record_id, old_data, new_data)
    values (auth.uid(), (select username from public.profiles where id = auth.uid()), TG_OP, TG_TABLE_NAME,
      coalesce(row_data->>'id', row_data->>'citizen_id', row_data->>'vehicle_id'),
      case when TG_OP in ('UPDATE', 'DELETE') then to_jsonb(old) end,
      case when TG_OP in ('INSERT', 'UPDATE') then to_jsonb(new) end);
  if TG_OP = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

