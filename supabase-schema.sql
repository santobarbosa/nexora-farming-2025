create table if not exists public.citizens (
  citizen_id text primary key,
  first_name text not null check (length(trim(first_name)) between 1 and 60),
  last_name text not null check (length(trim(last_name)) between 1 and 60),
  birthdate date not null,
  created_at timestamptz not null default now()
);

create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  company_name text not null check (length(trim(company_name)) between 1 and 100),
  owner_citizen_id text references public.citizens(citizen_id) on update cascade on delete set null,
  sector text not null default 'Landwirtschaft',
  description text not null default '',
  status text not null default 'pending' check (status in ('pending', 'active', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('privat', 'unternehmen')),
  citizen_id text references public.citizens(citizen_id) on update cascade on delete cascade,
  company_id bigint references public.companies(id) on update cascade on delete cascade,
  balance numeric(12, 2) not null default 0 check (balance >= 0),
  status text not null default 'pending' check (status in ('pending', 'active', 'blocked')),
  created_at timestamptz not null default now(),
  check ((type = 'privat' and citizen_id is not null and company_id is null)
      or (type = 'unternehmen' and company_id is not null and citizen_id is null))
);

create unique index if not exists accounts_one_active_citizen
  on public.accounts(citizen_id) where status = 'active';
create unique index if not exists accounts_one_active_company
  on public.accounts(company_id) where status = 'active';

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique,
  from_account_id bigint not null references public.accounts(id) on delete restrict,
  to_account_id bigint not null references public.accounts(id) on delete restrict,
  amount numeric(12, 2) not null check (amount > 0),
  reason text not null default 'Rechnung',
  status text not null default 'open' check (status in ('open', 'paid', 'cancelled')),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  check (from_account_id <> to_account_id)
);

create table if not exists public.vehicles (
  vehicle_id text primary key,
  name text not null,
  vehicle_class text not null,
  price numeric(12, 2) not null default 0 check (price >= 0),
  availability text not null default 'verkauf' check (availability in ('verkauf', 'miete')),
  status text not null default 'neu' check (status in ('neu', 'active', 'Occasion')),
  owner_citizen_id text references public.citizens(citizen_id) on update cascade on delete set null,
  company_id bigint references public.companies(id) on update cascade on delete set null,
  created_at timestamptz not null default now(),
